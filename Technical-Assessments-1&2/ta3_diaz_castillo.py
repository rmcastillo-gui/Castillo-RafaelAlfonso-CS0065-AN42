def get_int(prompt, minimum=0):
    """Safely obtain an integer."""
    while True:
        try:
            value = int(input(prompt))

            if value < minimum:
                print(f"Please enter a value of at least {minimum}.")
                continue

            return value

        except ValueError:
            print("Please enter a valid number.")


