def adapt_solution(new_case, retrieved_cases):
    """
    Adapt recommendations from the most similar cases.

    The first three retrieved cases are used as evidence.
    """

    top_cases = retrieved_cases[:3]

    print("\n" + "=" * 60)
    print("[REUSE AND ADAPTATION PHASE]")
    print("=" * 60)

    print(
        "\nThe system is adapting solutions from the most "
        "similar previous cases."
    )

    # --------------------------------------------------------
    # Evacuation
    # --------------------------------------------------------

    if "flood" in new_case["hazard"].lower():

        evacuation = (
            "Begin pre-emptive evacuation of low-lying and "
            "flood-prone urban areas. Prioritize residents "
            "near rivers, drainage channels and other high-risk zones."
        )

    else:

        evacuation = (
            "Begin evacuation of residents from areas identified "
            "as unsafe based on the expected disaster conditions."
        )

    # --------------------------------------------------------
    # Resources
    # --------------------------------------------------------

    if new_case["population"] >= 80000:

        resources = (
            "Deploy additional rescue teams and pre-position "
            "food, drinking water, medicine, generators and "
            "emergency communication equipment."
        )

    else:

        resources = (
            "Pre-position food, drinking water, medicine, "
            "generators and emergency response personnel."
        )

    # --------------------------------------------------------
    # Shelters
    # --------------------------------------------------------

    if new_case["shelters"] < 15:

        shelter_strategy = (
            "Available shelter capacity may be insufficient. "
            "Prepare temporary shelters and coordinate with "
            "nearby communities for additional evacuation space."
        )

    elif new_case["population"] / new_case["shelters"] > 5000:

        shelter_strategy = (
            "Activate all available shelters and prepare "
            "additional temporary shelters because expected "
            "population per shelter is high."
        )

    else:

        shelter_strategy = (
            "Activate available evacuation centers and "
            "distribute evacuees across facilities."
        )

    # --------------------------------------------------------
    # Show which cases influenced the solution
    # --------------------------------------------------------

    print("\nCases used as solution evidence:")

    for item in top_cases:
        print(
            f"- {item['case']['name']} "
            f"({item['score']:.2f}% similarity)"
        )

    return {
        "evacuation": evacuation,
        "resources": resources,
        "shelter_strategy": shelter_strategy
    }


