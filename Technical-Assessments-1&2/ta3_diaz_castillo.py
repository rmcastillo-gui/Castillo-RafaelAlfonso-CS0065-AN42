def load_cases():
    """Load the case base from JSON."""
    if not os.path.exists(CASE_FILE):
        save_cases(INITIAL_CASES)
        return INITIAL_CASES.copy()

    try:
        with open(CASE_FILE, "r", encoding="utf-8") as file:
            return json.load(file)
    except (json.JSONDecodeError, OSError):
        print("Warning: Could not read case base.")
        print("Restoring the original case base.\n")
        save_cases(INITIAL_CASES)
        return INITIAL_CASES.copy()


def save_cases(cases):
    """Save the case base to JSON."""
    with open(CASE_FILE, "w", encoding="utf-8") as file:
        json.dump(cases, file, indent=4)


