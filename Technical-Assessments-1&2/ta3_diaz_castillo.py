def similarity_score(new_case, old_case):
    """
    Calculate similarity between two cases.

    Total score = 100%

    Disaster type : 20%
    Hazard        : 20%
    Severity      : 15%
    Population    : 15%
    Rainfall      : 15%
    Shelters      : 15%
    """

    score = 0

    # Disaster type
    if new_case["disaster_type"].lower() == old_case["disaster_type"].lower():
        score += 20

    # Hazard
    if new_case["hazard"].lower() == old_case["hazard"].lower():
        score += 20
    else:
        # Partial match for related hazards
        new_hazard = new_case["hazard"].lower()
        old_hazard = old_case["hazard"].lower()

        if "flood" in new_hazard and "flood" in old_hazard:
            score += 12

        elif "wind" in new_hazard and "wind" in old_hazard:
            score += 12

    # Severity similarity
    severity_difference = abs(
        new_case["severity"] - old_case["severity"]
    )

    severity_similarity = max(
        0,
        1 - (severity_difference / 10)
    )

    score += severity_similarity * 15

    # Population similarity
    if new_case["population"] > 0 and old_case["population"] > 0:
        population_difference = abs(
            new_case["population"] - old_case["population"]
        ) / max(
            new_case["population"],
            old_case["population"]
        )

        population_similarity = max(
            0,
            1 - population_difference
        )

        score += population_similarity * 15

    # Rainfall similarity
    if new_case["rainfall"] > 0 and old_case["rainfall"] > 0:
        rainfall_difference = abs(
            new_case["rainfall"] - old_case["rainfall"]
        ) / max(
            new_case["rainfall"],
            old_case["rainfall"]
        )

        rainfall_similarity = max(
            0,
            1 - rainfall_difference
        )

        score += rainfall_similarity * 15

    # Shelter similarity
    if new_case["shelters"] > 0 and old_case["shelters"] > 0:
        shelter_difference = abs(
            new_case["shelters"] - old_case["shelters"]
        ) / max(
            new_case["shelters"],
            old_case["shelters"]
        )

        shelter_similarity = max(
            0,
            1 - shelter_difference
        )

        score += shelter_similarity * 15

    return score


def retrieve_cases(new_case, cases):
    """Retrieve and rank similar cases."""

    ranked_cases = []

    for case in cases:
        score = similarity_score(new_case, case)

        ranked_cases.append({
            "case": case,
            "score": score
        })

    ranked_cases.sort(
        key=lambda item: item["score"],
        reverse=True
    )

    return ranked_cases


