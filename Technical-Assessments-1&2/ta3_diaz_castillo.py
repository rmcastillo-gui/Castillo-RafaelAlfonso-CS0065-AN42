def main():

    cases = load_cases()

    print("\n" + "=" * 60)
    print(" CBR-BASED DISASTER RESPONSE DECISION SUPPORT SYSTEM")
    print("=" * 60)

    print(
        "\nCBR Cycle:"
        "\n  RETRIEVE -> REUSE/ADAPT -> REVISE -> RETAIN"
    )

    # --------------------------------------------------------
    # Step 1: New problem
    # --------------------------------------------------------

    new_case = get_new_problem()

    print("\n" + "=" * 60)
    print("[NEW PROBLEM DESCRIPTION]")
    print("=" * 60)

    print(f"Disaster Type       : {new_case['disaster_type']}")
    print(f"Expected Hazard     : {new_case['hazard']}")
    print(f"Severity            : {new_case['severity']}/10")
    print(
        f"Affected Population: "
        f"{new_case['population']:,}"
    )
    print(f"Expected Rainfall   : {new_case['rainfall']} mm")
    print(f"Available Shelters  : {new_case['shelters']}")

    # --------------------------------------------------------
    # Step 2: Retrieve
    # --------------------------------------------------------

    ranked_cases = retrieve_cases(
        new_case,
        cases
    )

    display_retrieval(ranked_cases)

    # --------------------------------------------------------
    # Step 3: Reuse / Adapt
    # --------------------------------------------------------

    solution = adapt_solution(
        new_case,
        ranked_cases
    )

    display_solution(solution)

    # --------------------------------------------------------
    # Step 4: Revise
    # --------------------------------------------------------

    outcome = collect_outcome()

    # --------------------------------------------------------
    # Step 5: Retain
    # --------------------------------------------------------

    retain_case(
        cases,
        new_case,
        solution,
        outcome
    )

    # --------------------------------------------------------
    # Step 6: Display updated case base
    # --------------------------------------------------------

    display_case_base(cases)

    print("\n" + "=" * 60)
    print("CBR CYCLE COMPLETE")
    print("=" * 60)

    print(
        "\nRETRIEVE -> REUSE/ADAPT -> REVISE -> RETAIN"
    )

    print(
        "\nThe new experience has become part of the "
        "system's future case evidence."
    )


