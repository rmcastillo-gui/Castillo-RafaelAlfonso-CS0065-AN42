# Inference Engine
def inference_engine(kb):
    laptop = kb["Laptop"]

    # Rule 1
    if laptop["Technical"]["RAM"] >= 8:
        print("Action: Laptop is suitable for multitasking.")

    # Rule 2
    if laptop["Technical"]["Processor"] == "Intel Core i5":
        print("Action: Laptop is suitable for school and work.")

    # Rule 3
    if laptop["Physical"]["Weight"] <= 2:
        print("Action: Laptop is portable.")

    # Rule 4
    if laptop["Physical"]["Color"] == "Black":
        print("Action: Laptop has a black exterior.")

    # Rule 5
    if laptop["Usage"]["Purpose"] == "School and work":
        print("Action: Laptop can be used for productivity tasks.")


# Run the inference engine
inference_engine(knowledge_base)

# Case-Based Reasoning Knowledge Base

case_base = {
    "Case 1": {
        "problem_features": {
            "device": "Laptop",
            "problem": "Overheating",
            "symptom": "Fan is loud"
        },
        "solution": "Clean the cooling fan and vents."
    },

    "Case 2": {
        "problem_features": {
            "device": "Laptop",
            "problem": "Slow performance",
            "symptom": "Programs take a long time to open"
        },
        "solution": "Close unnecessary programs and upgrade the RAM."
    },

    "Case 3": {
        "problem_features": {
            "device": "Laptop",
            "problem": "Battery draining quickly",
            "symptom": "Battery lasts less than 2 hours"
        },
        "solution": "Reduce power usage and replace the battery if necessary."
    }
}


# --------------------------------
# 1. RETRIEVE
# --------------------------------

def retrieve_case(new_problem):
    best_case = None
    highest_similarity = 0

    for case_name, case in case_base.items():
        similarity = 0

        for feature in new_problem:
            if feature in case["problem_features"]:
                if new_problem[feature] == case["problem_features"][feature]:
                    similarity += 1

        if similarity > highest_similarity:
            highest_similarity = similarity
            best_case = case_name

    return best_case


# --------------------------------
# 2. REUSE
# --------------------------------

def reuse_solution(case_name):
    return case_base[case_name]["solution"]


# --------------------------------
# 3. REVISE
# --------------------------------

def revise_solution(solution, new_problem):
    print("\nOriginal solution:", solution)

    # Example revision based on the new problem
    if new_problem["problem"] == "Overheating":
        solution = "Clean the cooling fan and vents, and make sure the laptop has proper airflow."

    print("Revised solution:", solution)

    return solution


# --------------------------------
# 4. RETAIN
# --------------------------------

def retain_case(new_problem, solution):
    new_case_number = len(case_base) + 1
    new_case_name = "Case " + str(new_case_number)

    case_base[new_case_name] = {
        "problem_features": new_problem,
        "solution": solution
    }

    print("\nNew case retained as:", new_case_name)


# --------------------------------
# NEW PROBLEM
# --------------------------------

new_problem = {
    "device": "Laptop",
    "problem": "Overheating",
    "symptom": "Fan is loud"
}


# CBR PROCESS

print("New Problem:", new_problem)

# Retrieve
retrieved_case = retrieve_case(new_problem)
print("\nRetrieved:", retrieved_case)

# Reuse
solution = reuse_solution(retrieved_case)
print("Reused Solution:", solution)

# Revise
solution = revise_solution(solution, new_problem)

# Retain
retain_case(new_problem, solution)


